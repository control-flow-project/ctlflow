import { execFileSync } from 'node:child_process';
import { readdirSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
const service = process.argv[2];
if (!['fleetd', 'fleet'].includes(service)) throw new Error('Select fleetd or fleet');
const root = fileURLToPath(new URL('../', import.meta.url)), product = join(root, 'services', service);
execFileSync(process.execPath, [join(root, 'scripts/build-service.mjs'), service], { cwd: root, stdio: 'inherit' });
const tests = readdirSync(join(product, 'dist/tests'), { recursive: true }).filter(file => file.endsWith('.test.js')).map(file => join(product, 'dist/tests', file));
if (!tests.length) throw new Error('A product must have tests');
execFileSync(process.execPath, ['--test', '--test-concurrency=1', '--test-timeout=180000', ...tests], { cwd: product, stdio: 'inherit' });
