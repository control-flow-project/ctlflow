import { cleanup } from '@ctlflow/crossfire-test-support/cleanup';
import assert from 'node:assert/strict';
import test from 'node:test';
import { randomUUID } from 'node:crypto';
import { mkdirSync, mkdtempSync } from 'node:fs';
import { join } from 'node:path';
import { chromium, expect } from '@playwright/test';
import { createWakeRule } from '@ctlflow/crossfire-domain/wake-up/manage';
import { readWakeRule } from '@ctlflow/crossfire-domain/wake-up/read';
import { nativeServer } from './support/native-server.js';
import { releaseFixture } from './release-fixture.js';
import { value } from './support/application.js';
import { checkPaperLayout } from '../tools/browser/layout.js';
import { COOKIE_NAME } from '../apps/server/src/http/transport.js';
import { browserOptions } from '@ctlflow/crossfire-test-support/tls';

test('Wake-ups browser CRUD, calendar selection, assignments, pagination and role visibility use the real APIs', { timeout: 120000 }, async scope => {
  const fixture = await nativeServer(scope, await releaseFixture()), { services, admin, origin } = fixture;
  const alice = await fixture.member('alice'), agent = await fixture.agent(admin.actor, 'ada'), foreign = await fixture.agent(alice.actor, 'guest');
  mkdirSync('.temp', { recursive: true }); const directory = mkdtempSync(join(process.cwd(), '.temp/wake-browser-'));
  const browser = await chromium.launch(browserOptions);
  cleanup(scope, () => browser.close());
  const context = await browser.newContext({ viewport: { width: 1600, height: 1100 } });
  await context.addCookies([{ name: COOKIE_NAME, value: admin.secret, url: origin, secure: true, httpOnly: true, sameSite: 'Strict' }]);
  const page = await context.newPage(), errors: string[] = [], failures: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (response.url().includes('/api/') && response.status() >= 400) failures.push(response.status() + ' ' + response.url()); });
  await page.goto(origin + '/manage/wake-ups'); await expect(page.getByRole('heading', { name: 'No Wake-ups', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'New Wake-up', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'New Wake-up', exact: true })).toBeVisible();
  await page.getByLabel('Name', { exact: true }).fill('Weekly reports');
  await page.getByLabel('Wake-up message', { exact: true }).fill('Fetch the latest report and summarize changes.');
  await page.getByLabel('Schedule', { exact: true }).selectOption('weekly');
  await expect(page.getByLabel('Cron expression', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Every day', exact: true }).click();
  await expect(page.locator('.schedule-preview')).toContainText('Every day');
  await page.getByRole('button', { name: 'Weekends', exact: true }).click();
  await expect(page.locator('.schedule-preview')).toContainText('Weekends');
  await page.getByLabel('Sun', { exact: true }).uncheck(); await page.getByLabel('Sat', { exact: true }).uncheck();
  await expect(page.getByRole('alert')).toHaveText('Choose at least one day for this schedule.');
  await page.getByRole('button', { name: 'Weekdays', exact: true }).click();
  await expect(page.locator('.schedule-preview')).toContainText('Weekdays');
  await page.getByLabel('Mon', { exact: true }).uncheck(); await page.getByLabel('Tue', { exact: true }).uncheck();
  await page.getByLabel('Fri', { exact: true }).uncheck(); await page.getByLabel('Sun', { exact: true }).check();
  await page.getByLabel('Time', { exact: true }).fill('01:00'); await page.getByLabel('Time zone', { exact: true }).fill('UTC');
  await page.getByRole('checkbox', { name: /^Attach ada/ }).check();
  await expect(page.getByRole('table', { name: 'Attached agents', exact: true }).locator('tbody tr')).toHaveCount(1);
  await checkPaperLayout(page); await page.screenshot({ path: join(directory, 'new-desktop.png'), fullPage: true });
  await Promise.all([page.waitForEvent('load'), page.getByRole('button', { name: 'Create Wake-up', exact: true }).click()]);
  const id = new URL(page.url()).pathname.split('/').at(-1)!;
  const created = value(readWakeRule(services, admin.actor, id));
  assert.deepEqual(created.schedule, { kind: 'cron', expression: '0 1 * * 0,3,4', timeZone: 'UTC' });
  assert.deepEqual(created.agents.map(agent => agent.agentId), [agent.id]);
  await expect(page.getByLabel('Wake-up message', { exact: true })).toHaveValue(created.message);
  await checkPaperLayout(page);
  await page.getByLabel('Schedule', { exact: true }).selectOption('cron');
  await page.getByLabel('Cron expression', { exact: true }).fill('0 22 * * WED');
  await page.getByLabel('Time zone', { exact: true }).fill('Asia/Kolkata');
  await page.getByLabel('Enabled', { exact: true }).uncheck();
  await Promise.all([page.waitForEvent('load'), page.getByRole('button', { name: 'Save Wake-up', exact: true }).click()]);
  assert.equal(value(readWakeRule(services, admin.actor, id)).enabled, false);
  await page.screenshot({ path: join(directory, 'detail-desktop.png'), fullPage: true });
  const message = { message: 'Test schedule.', schedule: { kind: 'interval' as const, seconds: 3600 }, enabled: true };
  for (let index = 0; index < 21; index++) value(createWakeRule(services, admin.actor, randomUUID(), { ...message, name: 'Admin schedule ' + index, agentIds: [] }, randomUUID()));
  const foreignId = randomUUID(); value(createWakeRule(services, alice.actor, foreignId, { ...message, name: 'Alice schedule', agentIds: [foreign.id] }, randomUUID()));
  await page.goto(origin + '/manage/wake-ups');
  await expect(page.getByRole('table', { name: 'Wake-ups', exact: true }).locator('tbody tr')).toHaveCount(20);
  await checkPaperLayout(page); await page.getByRole('link', { name: 'Next', exact: true }).click();
  await expect(page).toHaveURL(origin + '/manage/wake-ups?page=2');
  await expect(page.getByRole('table', { name: 'Wake-ups', exact: true }).locator('tbody tr')).toHaveCount(3);
  await page.getByLabel('Search Wake-ups', { exact: true }).fill('Weekly reports');
  await Promise.all([page.waitForEvent('load'), page.getByRole('button', { name: 'Search', exact: true }).click()]);
  await expect(page).toHaveURL(origin + '/manage/wake-ups?search=Weekly+reports');
  await expect(page.getByRole('table', { name: 'Wake-ups', exact: true }).locator('tbody tr'), await page.locator('body').innerText()).toHaveCount(1);
  await expect(page.getByRole('table', { name: 'Wake-ups', exact: true })).toContainText('Disabled');
  await page.setViewportSize({ width: 390, height: 844 }); await checkPaperLayout(page);
  await page.screenshot({ path: join(directory, 'list-mobile.png'), fullPage: true });
  await page.getByRole('link', { name: 'Weekly reports', exact: true }).click();
  await checkPaperLayout(page); await page.screenshot({ path: join(directory, 'detail-mobile.png'), fullPage: true });
  await page.getByRole('button', { name: 'Delete Wake-up', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal(value(readWakeRule(services, admin.actor, id)).id, id);
  await page.getByRole('button', { name: 'Delete Wake-up', exact: true }).click();
  await Promise.all([page.waitForEvent('load'), page.getByRole('dialog').getByRole('button', { name: 'Delete Wake-up', exact: true }).click()]);
  assert.equal(readWakeRule(services, admin.actor, id).ok, false);
  await page.goto(origin + '/manage/audit?pageSize=100');
  const audit = page.getByRole('table', { name: 'Management activity', exact: true });
  await expect(audit).toContainText('Create Wake-up'); await expect(audit).toContainText('Update Wake-up'); await expect(audit).toContainText('Delete Wake-up');
  const removal = audit.getByRole('row').filter({ hasText: 'Delete Wake-up' });
  await removal.getByText('View details', { exact: true }).click(); await expect(removal).toContainText('Deleted Wake-up “Weekly reports”.');
  const memberContext = await browser.newContext({ viewport: { width: 1600, height: 1100 } });
  await memberContext.addCookies([{ name: COOKIE_NAME, value: alice.secret, url: origin, secure: true, httpOnly: true, sameSite: 'Strict' }]);
  const memberPage = await memberContext.newPage(); await memberPage.goto(origin + '/manage/wake-ups');
  await expect(memberPage.getByRole('table', { name: 'Wake-ups', exact: true }).locator('tbody tr')).toHaveCount(1);
  await expect(memberPage.getByRole('table', { name: 'Wake-ups', exact: true })).toContainText('Alice schedule');
  await expect(memberPage.getByRole('columnheader', { name: 'Owner', exact: true })).toHaveCount(0);
  await expect(memberPage.getByRole('link', { name: 'Instance policy', exact: true })).toHaveCount(0);
  await memberPage.goto(origin + '/manage/wake-ups/' + foreignId); await checkPaperLayout(memberPage);
  await expect(memberPage.getByRole('table', { name: 'Choose agents', exact: true }).locator('tbody tr')).toHaveCount(1);
  assert.deepEqual(errors, []); assert.deepEqual(failures, []);
  scope.diagnostic('Real-browser screenshots: ' + directory);
});
