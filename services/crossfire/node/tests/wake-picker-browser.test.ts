import assert from 'node:assert/strict';
import test from 'node:test';
import { randomUUID } from 'node:crypto';
import { chromium, expect } from '@playwright/test';
import { cleanup } from '@ctlflow/crossfire-test-support/cleanup';
import { changeWakePolicy } from '@ctlflow/crossfire-domain/wake/change-policy';
import { COOKIE_NAME } from '../apps/server/src/http/transport.js';
import { nativeServer } from './support/native-server.js';
import { releaseFixture } from './release-fixture.js';
import { browserOptions } from '@ctlflow/crossfire-test-support/tls';
import { value } from './support/application.js';
import { checkPaperLayout } from '../tools/browser/layout.js';

test('wake audience has a reloadable URL, mobile page layout, multi-person drafts and concurrent replacement protection', { timeout: 120000 }, async scope => {
  const fixture = await nativeServer(scope, await releaseFixture()), { services, admin, origin } = fixture;
  const agent = await fixture.agent(admin.actor, 'picker');
  const people: Awaited<ReturnType<typeof fixture.member>>[] = [];
  for (let index = 0; index < 23; index++) people.push(await fixture.member('pick-person-' + String(index).padStart(2, '0')));
  const browser = await chromium.launch(browserOptions); cleanup(scope, () => browser.close());
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addCookies([{ name: COOKIE_NAME, value: admin.secret, url: origin, secure: true, httpOnly: true, sameSite: 'Strict' }]);
  const page = await context.newPage(), errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin + '/manage/agents/' + agent.id);
  const open = page.getByRole('link', { name: 'Choose who can wake', exact: true });
  const editor = page.locator('#wake-editor');
  const directory = editor.getByRole('table', { name: 'Available wake-up identities' });
  const selection = editor.getByRole('table', { name: 'Selected wake-up people and agents' });
  const revision = () => value(services.directory.agent(agent.id))!.principal.revision;
  const original = revision();
  await open.click(); await expect(page).toHaveURL(origin + '/manage/agents/' + agent.id + '/wake');
  await expect(page.getByRole('dialog')).toHaveCount(0); await expect(editor).toBeVisible();
  await page.reload(); await expect(editor).toBeVisible();
  await editor.getByLabel('Wake scope for ' + admin.member.principal.matrixUserId).selectOption('group');
  await editor.getByLabel('Search people or Matrix IDs').fill('pick-person-');
  await expect(directory.locator('tbody tr')).toHaveCount(20);
  const firstId = people[0]!.member.principal.matrixUserId;
  await editor.getByLabel('Allow ' + firstId, { exact: true }).check();
  await editor.getByLabel('Wake scope for ' + firstId).selectOption('group');
  await editor.getByRole('navigation', { name: 'Pagination', exact: true }).getByRole('button', { name: 'Next', exact: true }).click();
  await expect(directory.locator('tbody tr')).toHaveCount(3);
  await expect(selection).toContainText(firstId); await expect(selection).toContainText(admin.member.principal.matrixUserId);
  const lastId = people.at(-1)!.member.principal.matrixUserId;
  await editor.getByLabel('Allow ' + lastId, { exact: true }).check();
  await editor.getByLabel('Search people or Matrix IDs').fill('no-matches');
  await expect(editor.getByText('No matches', { exact: true })).toBeVisible(); await expect(selection).toContainText(lastId);
  await editor.getByRole('link', { name: 'Cancel', exact: true }).click(); await expect(open).toBeVisible();
  assert.equal(revision(), original);
  assert.equal(await page.evaluate<string>('document.documentElement.style.overflow'), '');
  await page.setViewportSize({ width: 390, height: 844 }); await open.click();
  await expect(page).toHaveURL(origin + '/manage/agents/' + agent.id + '/wake'); await checkPaperLayout(page);
  await expect(selection.locator('tbody tr')).toHaveCount(1);
  await page.getByRole('link', { name: '← Agent rooms & access', exact: true }).click(); await expect(open).toBeVisible();
  await page.setViewportSize({ width: 1440, height: 1000 }); await open.click();
  await editor.getByLabel('Search people or Matrix IDs').fill(firstId);
  await editor.getByLabel('Allow ' + firstId, { exact: true }).check();
  await editor.getByLabel('Wake scope for ' + firstId).selectOption('group');
  await editor.getByRole('button', { name: 'Save wake-up policy', exact: true }).click(); await expect(page).toHaveURL(origin + '/manage/agents/' + agent.id);
  await expect(page.getByRole('table', { name: 'Selected wake-up people and agents' })).toContainText(firstId);
  assert(value(services.collection.wakeSenders({ agentId: agent.id })).some(sender => sender.senderPrincipalId === people[0]!.actor.principalId && sender.includeAgents));
  await open.click(); await editor.getByLabel('Wake scope for ' + firstId).selectOption('person');
  value(changeWakePolicy(services, admin.actor, agent.id, { expectedRevision: revision(), mode: 'humans', senders: [] }, randomUUID()));
  await editor.getByRole('button', { name: 'Save wake-up policy', exact: true }).click();
  await expect(editor.getByRole('alert')).toContainText('These settings changed elsewhere');
  await expect(selection).toContainText(firstId); await expect(editor.getByRole('button', { name: 'Save wake-up policy' })).toBeDisabled();
  await editor.getByRole('button', { name: 'Discard edits & load latest' }).click(); await expect(editor.getByLabel('Audience', { exact: true })).toHaveValue('humans');
  await expect(editor.getByRole('button', { name: 'Save wake-up policy' })).toBeDisabled();
  await editor.getByRole('link', { name: 'Cancel', exact: true }).click();
  assert.deepEqual(errors, []);
});
