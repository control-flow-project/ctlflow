import test from 'node:test';
import assert from 'node:assert/strict';
import { nativeServer } from './support/native-server.js';
import { releaseFixture } from './release-fixture.js';
import { value } from './support/application.js';
import { createMemberInvitation, revokeMemberInvitation } from '@ctlflow/crossfire-domain/member/invitation';
import { listInvitations, readInvitation } from '@ctlflow/crossfire-domain/member/read-member';
import { changeInstancePolicy } from '@ctlflow/crossfire-domain/policy/change-policy';
import { registrationStage } from '../apps/server/src/http/registration.js';
import { session as parseSession } from '@ctlflow/crossfire-contracts/schema/response';
import { changeMember } from '@ctlflow/crossfire-domain/member/change-member';
test('normal Element signup requires a link in invitation mode and never grants administrator authority through open signup', { timeout: 120000 }, async scope => {
  const fixture = await nativeServer(scope, await releaseFixture());
  const { services, origin, admin } = fixture;
  const unsupported = await fetch(origin + '/_matrix/client/v3/register');
  assert.equal(unsupported.status, 405);
  assert.equal(unsupported.headers.get('allow'), 'POST');
  const post = (body: unknown, cookie = '') => fetch(origin + '/_matrix/client/v3/register', { method: 'POST', headers: { Origin: origin, Cookie: cookie, 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  const account = { username: 'invited-' + 'x'.repeat(92), password: 'private-password-12345', device_id: 'ELEMENT_DEVICE' };
  const verifyManagement = async (accessToken: string, username: string) => {
    const response = await fetch(origin + '/api/sessions', { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ nativeAccessToken: accessToken }) });
    assert.equal(response.status, 201, await response.clone().text());
    const body = await response.json() as { data: unknown };
    const session = value(parseSession(body.data));
    assert.equal(session.member.displayName, username);
    const before = value(services.directory.member(session.member.memberId))!;
    for (const displayName of ['', 'x'.repeat(101), 'invalid\u0000label']) {
      assert.equal(changeMember(services, admin.actor, before.principal.id, { expectedRevision: before.principal.revision, displayName }, 'invalid-label').ok, false);
    }
    assert.equal(value(services.directory.member(before.principal.id))!.principal.revision, before.principal.revision);
  };
  const challengeFor = async (input: unknown) => {
    const response = await post(input);
    assert.equal(response.status, 401);
    const body = await response.json() as { session: string; flows: { stages: string[] }[] };
    assert.deepEqual(body.flows, [{ stages: [registrationStage] }]);
    return body.session;
  };
  const confirmationUrl = (session: string) => origin + '/_matrix/client/v3/auth/' + registrationStage + '/fallback/web?session=' + session;
  const authorize = async (session: string, cookie = '') => {
    const page = await fetch(confirmationUrl(session), { headers: { Cookie: cookie } });
    assert.equal(page.status, 200, await page.clone().text());
    const nonce = /name="nonce" value="([A-Za-z0-9_-]{43})"/u.exec(await page.text())![1]!;
    const confirmed = await fetch(confirmationUrl(session), { method: 'POST', headers: { Origin: origin, Cookie: cookie, 'Content-Type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams({ nonce }) });
    assert.equal(confirmed.status, 200);
    assert.match(confirmed.headers.get('set-cookie')!, /Max-Age=0/u);
  };
  const deniedSession = await challengeFor(account);
  assert.equal((await fetch(confirmationUrl(deniedSession))).status, 403);
  assert.equal((await post({ ...account, auth: { session: deniedSession, type: 'm.login.dummy' } })).status, 400);
  assert.equal((await post({ ...account, auth: { session: deniedSession, type: registrationStage } })).status, 401);
  assert.equal((await (await fetch(origin + '/config.json')).json() as { disable_registration: boolean }).disable_registration, true);
  const invitation = value(createMemberInvitation(services, admin.actor, { roleCode: 'member', expiresSeconds: 600 }, 'invitation'));
  const claim = await fetch(origin + '/api/member-invitations/' + invitation.invitationId + '/claim', { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ claimSecret: invitation.claimSecret }) });
  assert.equal(claim.status, 200);
  const cookie = claim.headers.get('set-cookie')!.split(';')[0]!;
  assert(claim.headers.get('set-cookie')!.startsWith('__Host-crossfire-invitation='));
  for (const flag of ['HttpOnly', 'Secure', 'Path=/', 'SameSite=Strict']) assert(claim.headers.get('set-cookie')!.includes(flag));
  assert.equal((await (await fetch(origin + '/config.json', { headers: { Cookie: cookie.replace('__Host-crossfire-invitation=', 'crossfire_invitation=') } })).json() as { disable_registration: boolean }).disable_registration, true);
  assert.equal((await fetch(confirmationUrl(deniedSession), { headers: { Cookie: cookie + '; ' + cookie } })).status, 403);
  assert.equal((await (await fetch(origin + '/config.json', { headers: { Cookie: cookie } })).json() as { disable_registration: boolean }).disable_registration, false);
  const session = await challengeFor(account);
  assert.equal((await fetch(confirmationUrl(session), { method: 'POST', headers: { Origin: 'https://elsewhere.invalid', Cookie: cookie, 'Content-Type': 'application/x-www-form-urlencoded' }, body: 'nonce=invalid' })).status, 403);
  await authorize(session, cookie);
  assert.equal((await post({ ...account, username: 'switched-person', auth: { session } })).status, 400);
  const created = await post({ auth: { session } });
  assert.equal(created.status, 200, await created.clone().text());
  const credentials = await created.json() as { user_id: string; access_token: string; device_id: string };
  assert.equal(credentials.device_id, 'ELEMENT_DEVICE');
  const identity = value(await services.matrix.identify(credentials.access_token));
  assert.equal(identity, credentials.user_id);
  await verifyManagement(credentials.access_token, account.username);
  const principal = value(services.directory.principalByMatrixId(identity))!;
  assert.equal(value(services.directory.member(principal.id))!.role.roleCode, 'member');
  const usedSession = await challengeFor({ ...account, username: 'another-person' });
  assert.equal((await fetch(confirmationUrl(usedSession), { headers: { Cookie: cookie } })).status, 403);
  assert.equal((await fetch(origin + '/api/member-invitations/' + invitation.invitationId + '/acceptance', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' })).status, 404);
  const policy = value(services.repositories.instancePolicy.find({ id: 'instance' }))!;
  value(changeInstancePolicy(services, admin.actor, { ...policy, expectedRevision: policy.revision, signupMode: 'open' }, 'open'));
  assert.equal((await (await fetch(origin + '/config.json')).json() as { disable_registration: boolean }).disable_registration, false);
  const openUsername = 'open-' + 'x'.repeat(95);
  const openSession = await challengeFor({ username: openUsername, password: 'another-private-password' });
  await authorize(openSession);
  const registered = await post({ auth: { session: openSession } });
  assert.equal(registered.status, 200, await registered.clone().text());
  const openAccount = await registered.json() as { user_id: string; access_token: string };
  await verifyManagement(openAccount.access_token, openUsername);
  const openPrincipal = value(services.directory.principalByMatrixId(openAccount.user_id))!;
  assert.equal(value(services.directory.member(openPrincipal.id))!.role.roleCode, 'member');
  assert.equal((await post({ username: 'agent-forbidden', password: 'another-private-password', auth: { session: openSession } })).status, 400);
  const rejectedSession = await challengeFor({ username: 'agent-forbidden', password: 'another-private-password' });
  await authorize(rejectedSession);
  assert.equal((await post({ auth: { session: rejectedSession } })).status, 400);
  assert.equal(value(await services.matrix.exists('@agent-forbidden:' + services.instance.serverName)), false);
  const administratorInvitation = value(createMemberInvitation(services, admin.actor, { roleCode: 'administrator', expiresSeconds: 600 }, 'administrator-invitation'));
  const claimedAdministrator = await fetch(origin + '/api/member-invitations/' + administratorInvitation.invitationId + '/claim', { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ claimSecret: administratorInvitation.claimSecret }) });
  const administratorCookie = claimedAdministrator.headers.get('set-cookie')!.split(';')[0]!;
  const administratorSession = await challengeFor({ username: 'invited-admin', password: 'another-private-password' });
  await authorize(administratorSession, administratorCookie);
  const administratorResponse = await post({ auth: { session: administratorSession } });
  assert.equal(administratorResponse.status, 200);
  const administratorAccount = await administratorResponse.json() as { user_id: string };
  const administratorPrincipal = value(services.directory.principalByMatrixId(administratorAccount.user_id))!;
  assert.equal(value(services.directory.member(administratorPrincipal.id))!.role.roleCode, 'administrator');
  const policyBeforeClosing = value(services.repositories.instancePolicy.find({ id: 'instance' }))!;
  const closingSession = await challengeFor({ username: 'closing-person', password: 'another-private-password' });
  await authorize(closingSession);
  value(changeInstancePolicy(services, admin.actor, { ...policyBeforeClosing, expectedRevision: policyBeforeClosing.revision, signupMode: 'invitation' }, 'close'));
  assert.equal((await post({ auth: { session: closingSession } })).status, 403);
  assert.equal(value(await services.matrix.exists('@closing-person:' + services.instance.serverName)), false);
});
test('invitation issuers follow policy and members cannot elevate roles or inspect another issuer’s invitations', { timeout: 120000 }, async scope => {
  const fixture = await nativeServer(scope, await releaseFixture()), { services, admin } = fixture;
  const alice = await fixture.member('alice'), bob = await fixture.member('bob');
  assert.equal(createMemberInvitation(services, alice.actor, { roleCode: 'member', expiresSeconds: 600 }, 'denied').ok, false);
  const policy = value(services.repositories.instancePolicy.find({ id: 'instance' }))!;
  value(changeInstancePolicy(services, admin.actor, { ...policy, expectedRevision: policy.revision, invitationIssuers: 'members' }, 'allow'));
  const invite = value(createMemberInvitation(services, alice.actor, { roleCode: 'member', expiresSeconds: 600 }, 'allowed'));
  assert.equal(createMemberInvitation(services, alice.actor, { roleCode: 'administrator', expiresSeconds: 600 }, 'elevate').ok, false);
  assert.equal(value(listInvitations(services, alice.actor, { page: 1, pageSize: 1 })).items[0]!.id, invite.invitationId);
  assert.equal(value(listInvitations(services, bob.actor, { page: 1, pageSize: 1 })).totalItems, 0);
  assert.equal(readInvitation(services, bob.actor, invite.invitationId).ok, false);
  assert.equal(revokeMemberInvitation(services, bob.actor, invite.invitationId, 'foreign').ok, false);
  value(revokeMemberInvitation(services, admin.actor, invite.invitationId, 'admin'));
});
