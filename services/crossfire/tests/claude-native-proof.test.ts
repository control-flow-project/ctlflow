import assert from 'node:assert/strict';
import test from 'node:test';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync, symlinkSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { discoverClaude } from '@crossfire/adapter-claude/discovery';
import { connectClaude } from '@crossfire/adapter-claude/connection';
import { claudeContextFile } from '@crossfire/adapter-claude/hook';
import { readJson } from '@crossfire/adapter-filesystem/index';
import type { ClaudeContext } from '@crossfire/adapter-claude/context';
import { claudeProvider } from './support/claude-provider.js';

for (const forced of [false, true]) test('stock Claude confirms native input and stops on ' + (forced ? 'forced process death' : 'clean native exit'), { timeout: 60000 }, async scope => {
  mkdirSync(join(process.cwd(), '.temp'), { recursive: true });
  const directory = mkdtempSync(join(process.cwd(), '.temp/claude-native-'));
  const home = join(directory, 'home'); mkdirSync(home, { mode: 0o700 });
  mkdirSync(join(directory, '.crossfire'), { mode: 0o700 });
  symlinkSync(resolve('dist/crossfire-client.mjs'), join(directory, '.crossfire/client.mjs'));
  const module = pathToFileURL(resolve('packages/adapter-claude/dist/hook.js')).href;
  const script = `import fs from "node:fs";import {installClaudeHook} from ${JSON.stringify(module)};installClaudeHook(process.cwd());fs.writeFileSync("native-context.json",JSON.stringify(Object.fromEntries(["CLAUDE_CODE_SESSION_ID","CLAUDE_CODE_MESSAGING_SOCKET","CLAUDE_CODE_MESSAGING_TOKEN","CLAUDE_PID","CLAUDE_CONFIG_DIR"].map(key=>[key,process.env[key]]))),{mode:384});await new Promise(resolve=>setTimeout(resolve,1000));`;
  const capture = 'node --input-type=module -e ' + "'" + script.replaceAll("'", "'\\''") + "'";
  const provider = await claudeProvider(scope, capture, 2);
  const config = JSON.stringify({ mcpServers: {} });
  const child = spawn('claude', ['--print', '--verbose', '--input-format', 'stream-json', '--output-format', 'stream-json', '--model', 'claude-sonnet-4-6', '--permission-mode', 'default', '--allowedTools', 'Bash', '--mcp-config', config, '--strict-mcp-config'], {
    cwd: directory, env: { ...process.env, HOME: home, CLAUDE_CONFIG_DIR: join(home, '.claude'), ANTHROPIC_API_KEY: 'fixture-not-a-real-key', ANTHROPIC_BASE_URL: provider.base, CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC: '1' }, stdio: ['pipe', 'pipe', 'pipe'],
  });
  scope.after(() => child.kill('SIGTERM'));
  let output = '', errors = '';
  child.stdout.on('data', data => { output += String(data); }); child.stderr.on('data', data => { errors += String(data); });
  child.stdin.write(JSON.stringify({ type: 'user', message: { role: 'user', content: 'Bootstrap fixture.' } }) + '\n');
  const deadline = Date.now() + 45000;
  const contextFile = join(directory, 'native-context.json');
  while ((!existsSync(contextFile) || provider.requests.length < 2) && child.exitCode === null && Date.now() < deadline) await new Promise<void>(resolve => setTimeout(resolve, 100));
  assert(existsSync(contextFile) && provider.requests.length === 2, output + errors);
  const context = readJson<NodeJS.ProcessEnv>(contextFile);
  const registry = join(home, '.claude', 'sessions', context.CLAUDE_PID + '.json');
  writeFileSync(join(directory, 'registry.json'), readFileSync(registry));
  const descriptor = claudeContextFile(directory, context.CLAUDE_CODE_SESSION_ID!);
  assert(existsSync(descriptor), 'Project hook must capture exact native history without restart: ' + errors + output);
  const discovered = discoverClaude(directory, context);
  const stop = new AbortController();
  assert.equal(discovered.session, context.CLAUDE_CODE_SESSION_ID);
  const connection = await connectClaude(readJson<ClaudeContext>(descriptor), { journal: join(directory, 'receipt.json'), pollMs: 100, timeoutMs: 100 }, stop.signal);
  scope.after(() => connection.close());
  let delivered = false;
  const accepted = connection.deliver('Crossfire fixture input.\nSecond line.', 'fixture-input').then(() => { delivered = true; });
  await new Promise<void>(resolve => setTimeout(resolve, 250));
  assert.equal(delivered, false, 'Busy queued input must not be acknowledged before native publication');
  provider.release();
  await accepted;
  await connection.deliver('Crossfire fixture input.\nSecond line.', 'fixture-input');
  assert.equal(delivered, true);
  assert(!('turnControl' in connection), 'Peer messaging does not invent native turn interruption');
  if (!forced) await new Promise<void>(resolve => setTimeout(resolve, 31000));
  assert(!connection.signal.aborted, 'Native listener lifetime is independent of short-lived publication sockets');
  await connection.deliver('Idle peer publication after the native socket deadline.', 'fixture-idle');
  if (forced) child.kill('SIGKILL'); else child.stdin.end();
  await once(child, 'exit');
  writeFileSync(join(directory, 'evidence.json'), JSON.stringify({ output, errors, requests: provider.requests }, null, 2));
  const native = readJson<ClaudeContext>(descriptor);
  const transcript = readFileSync(native.transcript, 'utf8');
  writeFileSync(join(directory, 'transcript.jsonl'), transcript);
  assert(provider.requests.length >= 3, errors + output);
  assert(transcript.includes('fixture-input'), 'Native socket receipt must preserve exact input correlation');
  assert.equal(transcript.split('\n').filter(line => line.includes('"uuid":"fixture-input"')).length, 1);
  assert.equal(transcript.split('\n').filter(line => line.includes('"uuid":"fixture-idle"')).length, 1);
  const { until } = await import('../scripts/test-support/listener.js');
  await until(() => connection.signal.aborted, 'Native engine closure stops this listener connection');
});
