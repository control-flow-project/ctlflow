import assert from 'node:assert/strict';
import test from 'node:test';
import { execFile, execFileSync } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { randomUUID } from 'node:crypto';
import { discoverPi } from '@crossfire/adapter-pi/discovery';
import { readJson } from '@crossfire/adapter-filesystem/index';
import { piCall, piDescriptor } from '@crossfire/adapter-pi/protocol';
import { builtClient, builtRelease } from '../scripts/test-support/release.js';
import { nativeServer } from './support/native-server.js';
import { updatedRelease } from './release-fixture.js';
import { until } from '../scripts/test-support/listener.js';
import { decideEnrollment } from '@crossfire/domain/enrollment/decide';
import { value } from './support/application.js';

const execute = promisify(execFile);
type NativeSession = { sessionId: string; bindExtensions: (options: { mode: 'rpc'; onError: (error: unknown) => void }) => Promise<void>;
  reload: () => Promise<void>; dispose: () => void };
type NativeSettings = { setProjectTrusted: (trusted: boolean) => void };

test('native Pi reload activates installation and software upgrades without replacing the approved identity', { timeout: 120000 }, async scope => {
  mkdirSync('.temp', { recursive: true });
  const directory = mkdtempSync(join(process.cwd(), '.temp/pi-reload-'));
  const project = join(directory, 'project'), agent = join(directory, 'agent');
  mkdirSync(project, { mode: 0o700 }); mkdirSync(agent, { mode: 0o700 });
  execFileSync('git', ['init', '--quiet', project]);
  writeFileSync(join(agent, 'settings.json'), JSON.stringify({ retry: { enabled: false }, compaction: { enabled: false }, cacheWarming: { mode: 'off' } }));
  const module = pathToFileURL(join(execFileSync('npm', ['root', '-g'], { encoding: 'utf8' }).trim(), '@earendil-works/pi-coding-agent/dist/core/sdk.js')).href;
  const sdk = await import(module) as { createAgentSession: (options: { cwd: string; agentDir: string; settingsManager: NativeSettings; tools: string[]; thinkingLevel: 'off' }) => Promise<{ session: NativeSession }> };
  const settingsModule = await import(new URL('./settings-manager.js', module).href) as { SettingsManager: { create: (project: string, agent: string) => NativeSettings } };
  const settings = settingsModule.SettingsManager.create(project, agent);
  settings.setProjectTrusted(true);
  const errors: unknown[] = [];
  const { session: native } = await sdk.createAgentSession({ cwd: project, agentDir: agent, settingsManager: settings, tools: [], thinkingLevel: 'off' });
  await native.bindExtensions({ mode: 'rpc', onError: error => errors.push(error) });
  scope.after(async () => { settings.setProjectTrusted(false); await native.reload(); native.dispose(); });
  const release = { ...builtRelease().release };
  const fixture = await nativeServer(scope, release), { origin, services, admin } = fixture;
  const owner = admin.member.principal.matrixUserId;
  const { CODEX_THREAD_ID: _codex, CLAUDE_CODE_SESSION_ID: _claude, CROSSFIRE_PI_CONNECTION: _pi, ...environment } = process.env;
  const arguments_ = ['--profile', 'charlie', 'agent', 'connect', '--runtime', 'pi', '--server', origin, '--owner', owner];
  const initial = await execute(process.execPath, [builtClient(), ...arguments_], { cwd: project, env: environment, timeout: 30000, maxBuffer: 256 * 1024 });
  assert(initial.stdout.includes('runtime-setup-required') && initial.stdout.includes('/reload'), initial.stdout);
  const descriptor = join(project, '.crossfire/runtime/pi', native.sessionId + '.json');
  assert(!existsSync(descriptor), 'Downloading an extension cannot hot-load native code');
  assert.equal(value(services.directory.agentIds(admin.actor.principalId)).length, 0);
  await native.reload();
  assert.deepEqual(errors, []);
  assert(existsSync(descriptor), 'Pi native reload activates its trusted project extension');
  const discovered = discoverPi(project, { CROSSFIRE_PI_CONNECTION: descriptor });
  assert.equal(discovered.session, native.sessionId);
  const client = join(project, '.crossfire/client.mjs');
  const approvedProfile = join(project, '.crossfire/profiles/charlie.json');
  const installation = readJson<{ release: string }>(join(project, '.crossfire/software', release.manifest.release, 'manifest.json'));
  assert.equal(installation.release, release.manifest.release);
  const enrollment = execute(process.execPath, [client, 'agent', 'connect'], { cwd: project, env: { ...environment, CROSSFIRE_PI_CONNECTION: descriptor }, timeout: 60000 });
  void enrollment.catch(() => {});
  const pending = join(project, '.crossfire/profiles/charlie.pending.json');
  await until(() => existsSync(pending) && readJson<{ code: string }>(pending).code.length === 12);
  const request = readJson<{ code: string; request: string }>(pending);
  value(decideEnrollment(services, admin.actor, request.request, { expectedRevision: 0, decision: 'approve', verificationCode: request.code }, randomUUID()));
  await fixture.worker.drain();
  const connected = await enrollment;
  assert(connected.stdout.includes('"status": "listening"'), connected.stdout);
  scope.after(async () => { await execute(process.execPath, [client, 'agent', 'disconnect'], { cwd: project, env: environment }); });
  const identity = readFileSync(approvedProfile), old = piDescriptor(readJson<unknown>(descriptor));
  assert(old.ok);
  assert.equal(value(services.directory.agentIds(admin.actor.principalId)).length, 1);
  const tested = await execute(process.execPath, [client, 'agent', 'test'], { cwd: project, env: environment, timeout: 30000 });
  const diagnostic = JSON.parse(tested.stdout) as { status: string; listener: { test: { busy: boolean } } };
  assert.equal(diagnostic.status, 'passed');
  assert.equal(diagnostic.listener.test.busy, false);
  const updated = updatedRelease(release, 'crossfire-pi.mjs', release.files['crossfire-pi.mjs'].toString() + '\nexport const fixtureUpdated = true;\n');
  release.manifest = updated.manifest; release.files = updated.files;
  await assert.rejects(execute(process.execPath, [client, 'agent', 'connect'], { cwd: project, env: { ...environment, CROSSFIRE_PI_CONNECTION: descriptor }, timeout: 30000 }), /Pi native extension needs this verified update/);
  assert.deepEqual(readFileSync(approvedProfile), identity, 'An activation requirement must preserve approval and identity');
  await native.reload();
  await assert.rejects(piCall(old.value, { method: 'verify' }, new AbortController().signal), /closed|unavailable/);
  assert.deepEqual(errors, []);
  const current = discoverPi(project, { CROSSFIRE_PI_CONNECTION: descriptor });
  assert.equal(current.session, discovered.session);
  assert.notEqual(current.binding, discovered.binding);
  const resumed = await execute(process.execPath, [client, 'agent', 'connect'], { cwd: project, env: { ...environment, CROSSFIRE_PI_CONNECTION: descriptor }, timeout: 30000 });
  assert(resumed.stdout.includes('"status": "listening"'));
  assert(resumed.stdout.includes(updated.manifest.release));
  assert.deepEqual(readFileSync(approvedProfile), identity);
  assert.equal(value(services.directory.agentIds(admin.actor.principalId)).length, 1, 'Upgrade must not create another identity');
  assert(readFileSync(join(project, '.gitignore'), 'utf8').includes('.pi/extensions/crossfire.js'));
});
