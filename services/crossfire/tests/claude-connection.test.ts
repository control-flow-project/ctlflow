import assert from 'node:assert/strict';
import test from 'node:test';
import { spawn, execFile, execFileSync } from 'node:child_process';
import { promisify } from 'node:util';
import { once } from 'node:events';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { onboardingCommand } from '@crossfire/contracts/onboarding';
import { readJson } from '@crossfire/adapter-filesystem/index';
import { claudeContextFile } from '@crossfire/adapter-claude/hook';
import type { ClaudeContext } from '@crossfire/adapter-claude/context';
import { nativeOk } from '@crossfire/adapter-matrix/http';
import { API, segment } from '@crossfire/contracts/matrix';
import { reconcileRoomGrant } from '@crossfire/domain/room-access/reconcile-grant';
import { builtRelease } from '../scripts/test-support/release.js';
import { until } from '../scripts/test-support/listener.js';
import { nativeServer } from './support/native-server.js';
import { value } from './support/application.js';
import { claudeProvider } from './support/claude-provider.js';

const execute = promisify(execFile);

test('published bootstrap, native Claude activation, approval, Matrix delivery and reconnect reuse one identity', { timeout: 120000 }, async scope => {
  mkdirSync('.temp', { recursive: true });
  const directory = mkdtempSync(join(process.cwd(), '.temp/claude-connect-'));
  const project = join(directory, 'project'), home = join(directory, 'home');
  mkdirSync(project, { mode: 0o700 }); mkdirSync(home, { mode: 0o700 });
  execFileSync('git', ['init', '--quiet', project]);
  mkdirSync(join(project, '.claude'), { mode: 0o700 });
  writeFileSync(join(project, '.claude/settings.local.json'), JSON.stringify({ env: { FIXTURE_SETTING: 'preserved' } }));
  const release = builtRelease().release, fixture = await nativeServer(scope, release);
  const { services, origin, worker, admin } = fixture;
  const httpRequests: { path: string; status?: number; elapsed?: number }[] = [];
  fixture.router.on('request', (request, response) => {
    const entry: { path: string; status?: number; elapsed?: number } = { path: request.url ?? '' };
    const started = performance.now(); httpRequests.push(entry);
    response.once('finish', () => { entry.status = response.statusCode; entry.elapsed = performance.now() - started; });
  });
  const owner = admin.member.principal.matrixUserId;
  const keys = ['CLAUDE_CODE_SESSION_ID', 'CLAUDE_CODE_MESSAGING_SOCKET', 'CLAUDE_CODE_MESSAGING_TOKEN', 'CLAUDE_PID', 'CLAUDE_CONFIG_DIR'];
  const capture = `node -e 'require("node:fs").writeFileSync("native-context.json",JSON.stringify(Object.fromEntries(${JSON.stringify(keys)}.map(key=>[key,process.env[key]]))),{mode:384})'`;
  const command = onboardingCommand(origin, owner, release.manifest);
  const provider = await claudeProvider(scope, capture + '\n' + command);
  const { CODEX_THREAD_ID: _codex, CROSSFIRE_PI_CONNECTION: _pi, ...baseEnvironment } = process.env;
  const environment = { ...baseEnvironment, HOME: home, CLAUDE_CONFIG_DIR: join(home, '.claude'), CROSSFIRE_AGENT_NAME: 'charlie',
    ANTHROPIC_API_KEY: 'fixture-not-a-real-key', ANTHROPIC_BASE_URL: provider.base, CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC: '1' };
  const child = spawn('claude', ['--print', '--verbose', '--debug', 'hooks', '--debug-file', join(directory, 'native.log'), '--input-format', 'stream-json', '--output-format', 'stream-json', '--model', 'claude-sonnet-4-6',
    '--permission-mode', 'default', '--allowedTools', 'Bash', '--mcp-config', '{"mcpServers":{}}', '--strict-mcp-config'], { cwd: project, env: environment, stdio: ['pipe', 'pipe', 'pipe'] });
  scope.after(() => child.kill('SIGTERM'));
  let output = '', errors = '';
  scope.after(() => writeFileSync(join(directory, 'evidence.json'), JSON.stringify({ output, errors, requests: provider.requests, httpRequests }, null, 2)));
  child.stdout.on('data', data => { output += String(data); }); child.stderr.on('data', data => { errors += String(data); });
  child.stdin.write(JSON.stringify({ type: 'user', message: { role: 'user', content: 'Install the fixture project client.' } }) + '\n');
  const contextFile = join(project, 'native-context.json');
  const deadline = performance.now() + 45000;
  while ((!existsSync(contextFile) || provider.requests.length < 2) && child.exitCode === null && performance.now() < deadline) await new Promise<void>(resolve => setTimeout(resolve, 100));
  assert(existsSync(contextFile) && provider.requests.length === 2, errors + output);
  const nativeEnvironment: NodeJS.ProcessEnv = { ...environment, ...readJson<NodeJS.ProcessEnv>(contextFile) };
  const nativeContext = claudeContextFile(project, nativeEnvironment.CLAUDE_CODE_SESSION_ID!);
  assert(output.includes('runtime-setup-required'), output);
  assert(!existsSync(join(project, '.crossfire/profiles/charlie.pending.json')), 'Native activation precedes enrollment');
  assert.equal(value(services.directory.agentIds(admin.actor.principalId)).length, 0);
  const client = join(project, '.crossfire/client.mjs');
  await until(() => readFileSync(join(directory, 'native.log'), 'utf8').includes('Settings changed from localSettings'), 'Native Claude must load the installed project hook before its next tool call');
  provider.tool('node .crossfire/client.mjs agent connect');
  child.stdin.write(JSON.stringify({ type: 'user', message: { role: 'user', content: 'Connect the installed fixture client.' } }) + '\n');
  const pendingFile = join(project, '.crossfire/profiles/charlie.pending.json');
  await until(() => existsSync(pendingFile) && readJson<{ code: string }>(pendingFile).code.length === 12);
  assert(existsSync(nativeContext), 'The native PreToolUse hook supplies exact context before connection without restarting');
  const pending = readJson<{ code: string; request: string }>(pendingFile);
  const login = await fetch(origin + '/api/sessions', { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ nativeAccessToken: admin.token }) });
  assert.equal(login.status, 201);
  const session = await login.json() as { data: { csrfSecret: string } };
  const headers = { Origin: origin, Cookie: login.headers.get('set-cookie')!.split(';', 1)[0]!, 'X-Crossfire-CSRF': session.data.csrfSecret, 'Content-Type': 'application/json' };
  const approval = await fetch(origin + '/api/enrollments/' + pending.request + '/decision', { method: 'POST', headers,
    body: JSON.stringify({ expectedRevision: 0, decision: 'approve', verificationCode: pending.code }) });
  assert.equal(approval.status, 202); await worker.drain();
  await until(() => output.includes(JSON.stringify('"status": "listening"').slice(1, -1)) && provider.requests.length === 4, 'The native tool must finish approval and listener startup', 30000);
  assert(!output.includes(nativeEnvironment.CLAUDE_CODE_MESSAGING_TOKEN!));
  scope.after(async () => { await execute(process.execPath, [client, 'agent', 'disconnect'], { cwd: project, env: nativeEnvironment }); });
  const profilePath = join(project, '.crossfire/profiles/charlie.json'), profileBytes = readFileSync(profilePath);
  const profile = readJson<{ id: string }>(profilePath);
  const lease = readFileSync(join(project, '.crossfire/state/charlie/listener.json'));
  const repeated = await execute(process.execPath, [client, 'agent', 'connect'], { cwd: project, env: nativeEnvironment, timeout: 30000 });
  assert(repeated.stdout.includes('"status": "listening"'));
  assert.deepEqual(readFileSync(profilePath), profileBytes);
  assert.deepEqual(readFileSync(join(project, '.crossfire/state/charlie/listener.json')), lease);
  assert.equal(provider.requests.length, 4, 'Only the two explicit native fixture tool turns call the inert provider; reconnect does not submit model input');
  const ownerNative = { base: origin, token: admin.token };
  const room = value(await nativeOk(ownerNative, 'POST', API + '/createRoom', { name: 'Claude fixture', preset: 'private_chat' }));
  assert(typeof room.room_id === 'string');
  const grant = await fetch(origin + '/api/agents/' + profile.id + '/room-grants/' + segment(room.room_id), { method: 'PUT', headers,
    body: JSON.stringify({ expectedRevision: 0, expectedGeneration: null, accessMode: 'reply', powerLevel: null, muted: false }) });
  assert.equal(grant.status, 202, await grant.clone().text());
  value(await reconcileRoomGrant(services, profile.id, room.room_id));
  const account = readJson<{ account: { access_token: string } }>(profilePath).account;
  const joined = value(await nativeOk({ base: origin, token: account.access_token }, 'GET', API + '/joined_rooms'));
  assert(Array.isArray(joined.joined_rooms) && joined.joined_rooms.includes(room.room_id));
  await execute(process.execPath, [client, 'agent', 'disconnect'], { cwd: project, env: nativeEnvironment });
  const granted = await execute(process.execPath, [client, 'agent', 'connect'], { cwd: project, env: nativeEnvironment, timeout: 30000 });
  assert(granted.stdout.includes('"status": "listening"'));
  assert.deepEqual(readFileSync(profilePath), profileBytes);
  await until(() => httpRequests.some(request => request.path.startsWith(API + '/rooms/' + segment(room.room_id as string) + '/messages') && request.elapsed !== undefined),
    'The native listener must acquire the newly joined room before the live input control', 30000);
  const sent = value(await nativeOk(ownerNative, 'PUT', API + '/rooms/' + segment(room.room_id) + '/send/m.room.message/claude-input', { msgtype: 'm.text', body: 'Exact native Matrix input.' }));
  assert(typeof sent.event_id === 'string');
  const transcript = readJson<ClaudeContext>(nativeContext).transcript;
  await until(() => readFileSync(transcript, 'utf8').includes(sent.event_id as string), 'Matrix input must reach the existing native Claude session', 30000);
  const journal = join(project, '.crossfire/runtime/claude', nativeEnvironment.CLAUDE_CODE_SESSION_ID + '.receipt');
  await until(() => existsSync(journal) && readJson<{ pending: unknown; confirmed: unknown[] }>(journal).pending === null
    && readJson<{ confirmed: unknown[] }>(journal).confirmed.length === 0, 'Matrix acknowledgment must retire the native receipt', 30000);
  assert(readFileSync(join(project, '.gitignore'), 'utf8').includes('.claude/settings.local.json'));
  assert.equal(readJson<{ env: { FIXTURE_SETTING: string } }>(join(project, '.claude/settings.local.json')).env.FIXTURE_SETTING, 'preserved');
  await execute(process.execPath, [client, 'agent', 'disconnect'], { cwd: project, env: nativeEnvironment });
  const reconnect = await execute(process.execPath, [client, 'agent', 'connect'], { cwd: project, env: nativeEnvironment, timeout: 30000 });
  assert(reconnect.stdout.includes('"status": "listening"'));
  assert.deepEqual(readFileSync(profilePath), profileBytes);
  assert.equal(value(services.directory.agentIds(admin.actor.principalId)).length, 1);
  child.stdin.end(); await once(child, 'exit');
  await until(() => !existsSync(join(project, '.crossfire/state/charlie/listener.json')));
  writeFileSync(join(directory, 'evidence.json'), JSON.stringify({ output, errors, requests: provider.requests }, null, 2));
});
