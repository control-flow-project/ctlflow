import { cleanup } from '@ctlflow/crossfire-test-support/cleanup';
import assert from 'node:assert/strict';
import test from 'node:test';
import { mkdtempSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { piHost } from '@ctlflow/crossfire-adapter-pi/host';
import { piCall } from '@ctlflow/crossfire-adapter-pi/protocol';
import type { PiApi, PiContext } from '@ctlflow/crossfire-adapter-pi/native';

test('Pi native host enforces credentials, exact generation, bounded input and pre-publication cancellation', async scope => {
  mkdirSync('.temp', { recursive: true });
  const directory = mkdtempSync(join(process.cwd(), '.temp/pi-host-'));
  let session = 'aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee', idle = false;
  const branch: unknown[] = [{ id: 'initial', type: 'message' }];
  let append = true;
  const api: PiApi = { on: () => {}, sendMessage: input => { if (append) branch.push({ id: 'receipt', type: 'custom_message', ...input }); } };
  const context: PiContext = { cwd: directory, signal: undefined, isIdle: () => idle, isProjectTrusted: () => true, abort: () => { idle = true; },
    sessionManager: { getSessionId: () => session, getSessionFile: () => undefined, getLeafId: () => 'initial', getBranch: () => branch } };
  const host = await piHost(api, context, 'a'.repeat(64)); cleanup(scope, () => host.close());
  const signal = new AbortController().signal;
  assert.equal(await piCall(host.descriptor, { method: 'verify' }, signal), true);
  await assert.rejects(piCall({ ...host.descriptor, token: 'b'.repeat(43) }, { method: 'verify' }, signal), /403/);
  await assert.rejects(piCall({ ...host.descriptor, generation: 'bbbbbbbb-bbbb-cccc-dddd-eeeeeeeeeeee' }, { method: 'verify' }, signal), /409/);
  await assert.rejects(piCall(host.descriptor, { method: 'active' }, signal), /409/);
  const input = { text: 'Exact queued input.', messageId: 'queued', boundary: { leaf: 'initial' } };
  await piCall(host.descriptor, { method: 'publish', ...input }, signal);
  assert.equal(await piCall(host.descriptor, { method: 'received', ...input }, signal), 'waiting');
  assert.equal(branch.length, 1);
  assert.equal(await piCall(host.descriptor, { method: 'cancel', messageId: input.messageId, text: input.text }, signal), true);
  assert.equal(await piCall(host.descriptor, { method: 'received', ...input }, signal), 'cancelled');
  idle = true; host.end(); await new Promise<void>(resolve => setImmediate(resolve));
  assert.equal(branch.length, 1, 'Cancelled queued input must never reach the model');
  await piCall(host.descriptor, { method: 'publish', ...input }, signal);
  assert.equal(await piCall(host.descriptor, { method: 'received', ...input }, signal), true);
  assert.equal(await piCall(host.descriptor, { method: 'cancel', messageId: input.messageId, text: input.text }, signal), false);
  append = false;
  const delayed = { ...input, messageId: 'submitted-without-receipt' };
  await piCall(host.descriptor, { method: 'publish', ...delayed }, signal);
  assert.equal(await piCall(host.descriptor, { method: 'received', ...delayed }, signal), false);
  await assert.rejects(piCall(host.descriptor, { method: 'publish', ...input, messageId: 'cannot-overwrite' }, signal), /409/);
  const origin = await fetch(host.descriptor.endpoint, { method: 'POST', headers: { authorization: 'Bearer ' + host.descriptor.token, origin: 'http://evil.invalid' } });
  assert.equal(origin.status, 403);
  await assert.rejects(piCall(host.descriptor, { method: 'publish', messageId: 'oversized', text: 'x'.repeat(98305), boundary: { leaf: 'initial' } }, signal), /400/);
  session = 'cccccccc-bbbb-cccc-dddd-eeeeeeeeeeee';
  await assert.rejects(piCall(host.descriptor, { method: 'verify' }, signal), /409/);
  await host.close(); await host.close();
});
