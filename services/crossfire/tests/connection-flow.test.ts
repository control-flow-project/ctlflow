import { cleanup } from '@crossfire/test-support/cleanup';
import { nativeServer } from './support/native-server.js';
import { value } from './support/application.js';
import assert from 'node:assert/strict';
import { execFile, execFileSync } from 'node:child_process';
import { promisify } from 'node:util';
import { existsSync, mkdtempSync, mkdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import test from 'node:test';
import { nativeEngine, materialize } from '../scripts/test-support/native-engine.js';
import { nativeProvider } from '@crossfire/test-support/native-provider';
import { until } from '../scripts/test-support/listener.js';
import { builtRelease } from '../scripts/test-support/release.js';
import { readJson } from '@crossfire/adapter-filesystem/index';
import { onboardingCommand, onboardingUrl } from '@crossfire/contracts/onboarding';

const execute = promisify(execFile);

test('published bootstrap connects a real Codex session after native human approval with no model polling', { timeout: 120_000 }, async scope => {
  const directory = mkdtempSync(join(process.cwd(), '.temp/smooth-native-'));
  const home = join(directory, 'home'), project = join(directory, 'project');
  mkdirSync(home, { mode: 0o700 }); mkdirSync(project, { mode: 0o700 });
  execFileSync('git', ['init', '--quiet', project]);
  const provider = await nativeProvider(scope, home);
  const engine = await nativeEngine(scope, home, project, ['-c', 'sandbox_mode="danger-full-access"']);
  await materialize(engine, provider);
  const release = builtRelease().release, fixture = await nativeServer(scope, release);
  const { services, origin, worker, admin } = fixture;
  const human = { id: admin.member.principal.matrixUserId, token: admin.token };
  const environment = { ...process.env, RUNCODEX_CONNECTION_FILE: join(home, 'connection.json'), CODEX_THREAD_ID: engine.session, CROSSFIRE_AGENT_NAME: 'holmes' };
  const guide = await fetch(onboardingUrl(origin, human.id));
  assert.equal(guide.status, 200);
  const commands = [...(await guide.text()).matchAll(/```bash\n([\s\S]*?)\n```/gu)];
  assert.equal(commands.length, 1, 'The public setup guide has one canonical bootstrap command');
  const command = commands[0]![1]!;
  assert.equal(command, onboardingCommand(origin, human.id, release.manifest));
  const connection = execute('bash', ['-c', command], { cwd: project, env: environment, timeout: 60_000, maxBuffer: 256 * 1024 });
  void connection.catch(() => {});
  const pendingFile = join(project, '.crossfire/profiles/holmes.pending.json');
  await until(() => existsSync(pendingFile) && readJson<{ code: string }>(pendingFile).code.length === 12);
  const pending = readJson<{ code: string; request: string }>(pendingFile);
  assert.equal(value(services.directory.agentIds(admin.actor.principalId)).length, 0);
  assert.equal(provider.requests.length, 0);
  const login = await fetch(origin + '/api/sessions', { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ nativeAccessToken: human.token }) });
  assert.equal(login.status, 201);
  const session = await login.json() as { data: { csrfSecret: string } };
  const cookie = login.headers.get('set-cookie')!.split(';', 1)[0]!;
  const approval = await fetch(origin + '/api/enrollments/' + pending.request + '/decision', { method: 'POST',
    headers: { Origin: origin, Cookie: cookie, 'X-Crossfire-CSRF': session.data.csrfSecret, 'Content-Type': 'application/json' },
    body: JSON.stringify({ expectedRevision: 0, decision: 'approve', verificationCode: pending.code }) });
  assert.equal(approval.status, 202);
  await worker.drain();
  const result = await connection;
  assert(result.stdout.includes('"status": "listening"'));
  assert(result.stdout.includes('"status": "online"'));
  assert(!result.stdout.includes(engine.token));
  const client = join(project, '.crossfire/client.mjs');
  cleanup(scope, async () => { await execute(process.execPath, [client, 'agent', 'disconnect'], { cwd: project, env: environment }); });
  const profile = readFileSync(join(project, '.crossfire/profiles/holmes.json'));
  const lease = readFileSync(join(project, '.crossfire/state/holmes/listener.json'));
  const repeated = await execute('bash', ['-c', command], { cwd: project, env: { ...environment, CROSSFIRE_AGENT_NAME: '' }, timeout: 30_000 });
  assert(repeated.stdout.includes('"status": "listening"'));
  assert.deepEqual(readFileSync(join(project, '.crossfire/profiles/holmes.json')), profile);
  assert.deepEqual(readFileSync(join(project, '.crossfire/state/holmes/listener.json')), lease);
  assert.equal(value(services.directory.agentIds(admin.actor.principalId)).length, 1);
  assert.equal(provider.requests.length, 0, 'Setup and reconnect must not submit model input');
  assert(readFileSync(join(project, '.gitignore'), 'utf8').includes('.crossfire/'));
  await execute(process.execPath, [client, 'agent', 'disconnect'], { cwd: project, env: environment });
  assert(!existsSync(join(project, '.crossfire/state/holmes/listener.json')));
  provider.tool('exec_command', { cmd: 'node .crossfire/client.mjs agent connect', yield_time_ms: 10_000, max_output_tokens: 4096 });
  engine.notifications.length = 0;
  await engine.call('turn/start', { threadId: engine.session, input: [{ type: 'text', text: 'Connect this fixture project to Crossfire.', text_elements: [] }] });
  await until(() => engine.notifications.some(notice => notice.method === 'turn/completed'));
  const tool = engine.notifications.find(notice => notice.method === 'item/completed' &&
    (notice.params as { item?: { type?: string } }).item?.type === 'commandExecution');
  assert(tool, JSON.stringify(engine.notifications));
  const completed = tool.params as { item: { aggregatedOutput: string; exitCode: number } };
  assert.equal(completed.item.exitCode, 0, completed.item.aggregatedOutput);
  assert(completed.item.aggregatedOutput.includes('"status": "listening"'), completed.item.aggregatedOutput);
  const active = await execute(process.execPath, [client, 'agent', 'status'], { cwd: project, env: environment });
  assert.equal(JSON.parse(active.stdout).listener.ready, true, 'Listener survives the native tool and model turn finishing');
  assert.equal(provider.requests.length, 2, 'Only the explicit fixture tool turn calls the inert provider');
  assert.deepEqual(readFileSync(join(project, '.crossfire/profiles/holmes.json')), profile);
  engine.child.kill('SIGTERM'); await engine.ended;
  await until(() => !existsSync(join(project, '.crossfire/state/holmes/listener.json')));
  const offline = await execute(process.execPath, [client, 'agent', 'status'], { cwd: project, env: environment });
  assert.equal(JSON.parse(offline.stdout).listener, null);
  await assert.rejects(execute(process.execPath, [client, 'agent', 'connect'], { cwd: project, env: environment, timeout: 30_000 }), /Codex WebSocket connection failed/);
  assert(!existsSync(join(project, '.crossfire/state/holmes/listener.json')));
  assert.deepEqual(readFileSync(join(project, '.crossfire/profiles/holmes.json')), profile);
  const log = readFileSync(join(project, '.crossfire/state/holmes/listener.log'), 'utf8');
  assert.match(log, /Codex WebSocket disconnected; listener stopped/);
  assert.doesNotMatch(log, /ERR_IPC_CHANNEL_CLOSED|Unhandled 'error'/);
});
