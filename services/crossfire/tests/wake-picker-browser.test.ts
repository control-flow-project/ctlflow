import assert from 'node:assert/strict';
import test from 'node:test';
import { randomUUID } from 'node:crypto';
import { chromium, expect } from '@playwright/test';
import { cleanup } from '@ctlflow/crossfire-test-support/cleanup';
import { changeWakePolicy } from '@ctlflow/crossfire-domain/wake/change-policy';
import { COOKIE_NAME } from '../apps/server/src/http/transport.js';
import { nativeServer } from './support/native-server.js';
import { releaseFixture } from './release-fixture.js';
import { browserOptions } from './support/tls.js';
import { value } from './support/application.js';

test('wake picker preserves multi-person drafts, uses a full-screen mobile modal and rejects concurrent replacement', { timeout: 120000 }, async scope => {
  const fixture = await nativeServer(scope, await releaseFixture()), { services, admin, origin } = fixture;
  const agent = await fixture.agent(admin.actor, 'picker');
  const people: Awaited<ReturnType<typeof fixture.member>>[] = [];
  for (let index = 0; index < 23; index++) people.push(await fixture.member('pick-person-' + String(index).padStart(2, '0')));
  const browser = await chromium.launch(browserOptions); cleanup(scope, () => browser.close());
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addCookies([{ name: COOKIE_NAME, value: admin.secret, url: origin, secure: true, httpOnly: true, sameSite: 'Strict' }]);
  const page = await context.newPage(), errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin + '/manage/agents/' + agent.id);
  const open = page.getByRole('button', { name: 'Choose who can wake', exact: true });
  const dialog = page.getByRole('dialog', { name: 'Who can wake this agent?', exact: true });
  const directory = dialog.getByRole('table', { name: 'Available wake-up identities' });
  const selection = dialog.getByRole('table', { name: 'Selected wake-up people and agents' });
  const revision = () => value(services.directory.agent(agent.id))!.principal.revision;
  const original = revision();
  await open.click(); await expect(dialog).toBeVisible();
  await expect(dialog.getByLabel('Search people or Matrix IDs')).toBeFocused();
  await dialog.getByLabel('Wake scope for ' + admin.member.principal.matrixUserId).selectOption('group');
  await dialog.getByLabel('Search people or Matrix IDs').fill('pick-person-');
  await expect(directory.locator('tbody tr')).toHaveCount(20);
  const firstId = people[0]!.member.principal.matrixUserId;
  await dialog.getByLabel('Allow ' + firstId, { exact: true }).check();
  await dialog.getByLabel('Wake scope for ' + firstId).selectOption('group');
  await dialog.getByRole('navigation', { name: 'Pagination', exact: true }).getByRole('button', { name: 'Next', exact: true }).click();
  await expect(directory.locator('tbody tr')).toHaveCount(3);
  await expect(selection).toContainText(firstId); await expect(selection).toContainText(admin.member.principal.matrixUserId);
  const lastId = people.at(-1)!.member.principal.matrixUserId;
  await dialog.getByLabel('Allow ' + lastId, { exact: true }).check();
  await dialog.getByLabel('Search people or Matrix IDs').fill('no-matches');
  await expect(dialog.getByText('No matches', { exact: true })).toBeVisible(); await expect(selection).toContainText(lastId);
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click(); await expect(dialog).toHaveCount(0);
  assert.equal(revision(), original); await expect(open).toBeFocused();
  assert.equal(await page.evaluate<string>('document.documentElement.style.overflow'), '');
  await page.setViewportSize({ width: 390, height: 844 }); await open.click();
  const bounds = await dialog.boundingBox(); assert(bounds); assert.equal(Math.round(bounds.width), 390); assert.equal(Math.round(bounds.height), 844);
  await expect(selection.locator('tbody tr')).toHaveCount(1);
  for (let index = 0; index < 18; index++) { await page.keyboard.press('Tab'); assert(await page.evaluate<boolean>('document.querySelector("dialog").contains(document.activeElement)')); }
  await page.keyboard.press('Escape'); await expect(dialog).toHaveCount(0); await expect(open).toBeFocused();
  await page.setViewportSize({ width: 1440, height: 1000 }); await open.click();
  await dialog.getByLabel('Search people or Matrix IDs').fill(firstId);
  await dialog.getByLabel('Allow ' + firstId, { exact: true }).check();
  await dialog.getByLabel('Wake scope for ' + firstId).selectOption('group');
  await dialog.getByRole('button', { name: 'Save wake-up policy', exact: true }).click(); await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('table', { name: 'Selected wake-up people and agents' })).toContainText(firstId);
  assert(value(services.collection.wakeSenders({ agentId: agent.id })).some(sender => sender.senderPrincipalId === people[0]!.actor.principalId && sender.includeAgents));
  await open.click(); await dialog.getByLabel('Wake scope for ' + firstId).selectOption('person');
  value(changeWakePolicy(services, admin.actor, agent.id, { expectedRevision: revision(), mode: 'humans', senders: [] }, randomUUID()));
  await dialog.getByRole('button', { name: 'Save wake-up policy', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('These settings changed elsewhere');
  await expect(selection).toContainText(firstId); await expect(dialog.getByRole('button', { name: 'Save wake-up policy' })).toBeDisabled();
  await dialog.getByRole('button', { name: 'Discard edits & load latest' }).click(); await expect(dialog.getByLabel('Audience')).toHaveValue('humans');
  await expect(dialog.getByRole('button', { name: 'Save wake-up policy' })).toBeDisabled();
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.deepEqual(errors, []);
});
