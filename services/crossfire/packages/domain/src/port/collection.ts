import type { Result } from '@crossfire/kernel/result';
import type { Page, PageRequest } from './directory.js';
import type { EnrollmentItem } from '../enrollment/types.js';
import type { FleetInstance } from '../enrollment/types.js';
import type { AgentRoomGrant } from '../room-access/types.js';
import type { AgentRoomPermission } from '../room-access/types.js';
import type { AgentWakeSender } from '../room-access/types.js';
import type { ListenerRun } from '../activity/types.js';
import type { WakeNotice } from '../activity/types.js';
import type { PrincipalApplication } from '../identity/types.js';
import type { RoomGrantApplication } from '../room-access/types.js';
import type { EnrollmentRequest } from '../enrollment/types.js';
import type { AgentName } from '../enrollment/types.js';
import type { MemberInvitation } from '../activity/types.js';
import type { RolePermission } from '../authorization/types.js';
import type { Fleet } from '../enrollment/types.js';
import type { AuditEvent } from '../audit/types.js';

export type CollectionRepository = {
  enrollmentMetadata(enrollmentId: string): Result<{ key: string; value: string }[]>;
  fleetMetadata(fleetIds: string[]): Result<{ fleetId: string; key: string; value: string }[]>;
  enrollmentItems(input: { requestId: string }): Result<EnrollmentItem[]>;
  fleetInstances(input: { ownerId: string; fleetKey: string }): Result<FleetInstance[]>;
  roomGrants(input: { agentId: string }): Result<AgentRoomGrant[]>;
  roomPermissions(input: { agentId: string; roomId: string }): Result<AgentRoomPermission[]>;
  wakeSenders(input: { agentId: string }): Result<AgentWakeSender[]>;
  wakeSendersForAgents(agentIds: string[]): Result<AgentWakeSender[]>;
  listenerRuns(input: { agentId: string }): Result<ListenerRun[]>;
  pendingNotices(input: { now: number }): Result<WakeNotice[]>;
  noticeHistory(input: { receiverAgentId: string; senderMatrixId: string; since: number }): Result<WakeNotice[]>;
  duePrincipals(input: { now: number }): Result<PrincipalApplication[]>;
  dueRoomGrants(input: { now: number }): Result<RoomGrantApplication[]>;
  agentRoomApplications(input: { agentId: string }): Result<RoomGrantApplication[]>;
  expiredEnrollments(input: { now: number }): Result<EnrollmentRequest[]>;
  agentNamesByRequest(input: { requestId: string }): Result<AgentName[]>;
  claimedInvitations(input: { now: number }): Result<MemberInvitation[]>;
  rolePermissions(input: { roleCode: string }): Result<RolePermission[]>;
  enrollments(input: PageRequest & { ownerId?: string }): Result<Page<EnrollmentRequest>>;
  fleets(input: PageRequest & { ownerId?: string; search?: string }): Result<Page<Fleet>>;
  invitations(input: PageRequest & { createdByMemberId?: string }): Result<Page<MemberInvitation>>;
  audits(input: PageRequest & { ownerId?: string }): Result<Page<AuditEvent>>;
  pendingEnrollmentCount(ownerId?: string): Result<number>;
  pendingIdentityCount(ownerId?: string): Result<number>;
  memberSessionCount(memberId: string, now: number): Result<number>;
  removeExpiredSessions(now: number): Result<void>;
  invitationByClaim(matrixUserId: string): Result<MemberInvitation | null>;
};
