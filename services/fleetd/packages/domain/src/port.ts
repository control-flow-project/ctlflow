import type { Result } from '@ctlflow/crossfire-kernel/result';
import type { RuntimeAttachment } from '@ctlflow/crossfire-agent-core/terminal';
import type { ControllerState, ListenerControl } from '@ctlflow/crossfire-agent-core/listener-control-port';
import type { NativeSessionState } from '@ctlflow/crossfire-agent-core/runtime';
import type { Configuration, Registration, Roster, Operation, Approval, Instance, Controller, FleetDelivery, FleetMessageResult, DesiredIntent, RetainedContext, SetupInput, SetupConfiguration } from './model.js';
export type Registry = {
  registrations(): Result<Registration[]>;
  saveRegistrations(values: Registration[]): Result<void>;
  desiredIntent(): Result<DesiredIntent[]>;
  saveDesiredIntent(values: DesiredIntent[]): Result<void>;
  operations(): Result<Operation[]>;
  saveOperations(values: Operation[]): Result<void>;
  load(directory: string): Result<Configuration>;
  writeRoster(configuration: Configuration, roster: Roster): Result<Configuration>;
  setup(input: SetupInput): Result<SetupConfiguration>;
  completeSetup(operationId: string): Result<void>;
  retrySetup(previousId: string, operationId: string): Result<void>;
};
export type Running = { sessionId: string; signal: AbortSignal; nativeState(): NativeSessionState;
  resume(): Promise<Result<void>>;
  attachment(): Promise<Result<RuntimeAttachment>>;
  attachments(): Promise<Result<{ context: string; attachment: RuntimeAttachment }[]>>;
  contexts(): Promise<Result<RetainedContext[]>>; control: ListenerControl; close(): Promise<void> };
export type Execution = {
  connect(configuration: Configuration, signal: AbortSignal,
    control: { execute: (input: { operationId: string; instanceKey: string | null; action: 'start' | 'stop' | 'reset' }) => Promise<Result<{ status: 'succeeded' | 'failed'; errorMessage: string | null }>>;
      acknowledged(operationId: string): Result<void> }): Result<void>;
  connection(configuration: Configuration): ControllerState;
  delivery(configuration: Configuration, input: { expectedRevision: number; enabled: boolean }): Promise<Result<FleetDelivery>>;
  message(configuration: Configuration, input: { messageId: string; body: string }): Promise<Result<FleetMessageResult>>;
  disconnect(configuration: Configuration): Promise<void>;
  close(): Promise<void>;
  validate(configuration: Configuration): Result<void>;
  inspect(configuration: Configuration, signal: AbortSignal): Promise<Result<void>>;
  test(configuration: Configuration, instance: Instance): Promise<Result<void>>;
  prepare(configuration: Configuration, controller: Controller, signal: AbortSignal, approval: (approval: Approval) => void): Promise<Result<{ failed: { instanceKey: string; code: string; message: string }[] }>>;
  start(configuration: Configuration, instance: Instance, signal: AbortSignal, reason: 'operator' | 'recovery'): Promise<Result<Running>>;
  contexts(configuration: Configuration, instance: Instance): Promise<Result<RetainedContext[]>>;
  confirmStopped(configuration: Configuration, instance: Instance): Promise<Result<void>>;
  reset(configuration: Configuration, instance: Instance, resetId: string, signal: AbortSignal): Promise<Result<void>>;
  remove(configuration: Configuration, instance: Instance): Promise<Result<void>>;
  archive(configuration: Configuration): Promise<Result<void>>;
  update(configuration: Configuration, instance: Instance, releaseDirectory: string, signal: AbortSignal): Promise<Result<void>>;
};
export type Services = { registry: Registry; execution: Execution; controller: Controller; now(): number; id(): string;
  delay(milliseconds: number, signal: AbortSignal): Promise<void> };
